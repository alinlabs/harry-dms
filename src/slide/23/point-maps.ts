export function getStatusCategory(stage: string): string {
  const s = (stage || '').toLowerCase();
  if (
    s.includes('negotiat') ||
    s.includes('negosiasi') ||
    s.includes('kontrak') ||
    s.includes('mou') ||
    s.includes('closing') ||
    s.includes('peering') ||
    s.includes('konsesi')
  ) {
    return 'negosiasi_closing';
  }
  if (
    s.includes('proposal') ||
    s.includes('present') ||
    s.includes('rfp') ||
    s.includes('bidding') ||
    s.includes('tender') ||
    s.includes('evaluation') ||
    s.includes('review') ||
    s.includes('pitch')
  ) {
    return 'proposal_rfp';
  }
  if (
    s.includes('survey') ||
    s.includes('poc') ||
    s.includes('trial') ||
    s.includes('demo') ||
    s.includes('scoping')
  ) {
    return 'survey_poc';
  }
  return 'lead';
}


